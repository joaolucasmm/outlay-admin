/**
 * Writes the Java tenant API's demo seed (services/tenant-api/.../db/demo/R__demo_seed.sql)
 * from the web mock's fixtures, so both backends serve exactly the same demo data.
 *
 *   pnpm seed:export
 *
 * CI runs it and fails if the committed SQL is stale (ADR 0007).
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { seedEmployees } from '../apps/web/src/mocks/fixtures/employees';
import { seedCategories, seedPolicyRules } from '../apps/web/src/mocks/fixtures/program';
import { seedAuditEvents, seedTenants } from '../apps/web/src/mocks/fixtures/seed';

const OUT = fileURLToPath(
  new URL('../services/tenant-api/src/main/resources/db/demo/R__demo_seed.sql', import.meta.url),
);

type Value = string | number | boolean | null;

/** A SQL literal. MySQL treats backslash as an escape inside strings, so it is doubled. */
const literal = (value: Value): string => {
  if (value === null) return 'NULL';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? 'TRUE' : 'FALSE';
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "''")}'`;
};

/** ISO 8601 UTC to a DATETIME(3) literal. */
const datetime = (iso: string) => iso.replace('T', ' ').replace('Z', '');

const json = (value: unknown) => (value === undefined ? null : JSON.stringify(value));

/** Same normalization as NewTenant.nameKey in Java and sameTenantName in the domain. */
const nameKey = (name: string) => name.trim().replace(/\s+/g, ' ').toLowerCase();

function insert(table: string, columns: string[], rows: Value[][]): string | null {
  if (rows.length === 0) return null;
  const values = rows.map((row) => `  (${row.map(literal).join(', ')})`).join(',\n');
  return `INSERT INTO ${table} (${columns.join(', ')}) VALUES\n${values};\n`;
}

const sql = [
  '-- GENERATED by scripts/export-demo-seed.ts from apps/web/src/mocks/fixtures. Do not edit:',
  '-- change the fixtures and run `pnpm seed:export`. CI fails if this file is stale.',
  '-- Demo data, loaded only with the `demo` profile; POST /demo/reset runs this script again.',
  '',
  'DELETE FROM employees;',
  'DELETE FROM policy_rules;',
  'DELETE FROM categories;',
  'DELETE FROM audit_events;',
  'DELETE FROM tenants;',
  '',
  insert(
    'tenants',
    ['id', 'name', 'name_key', 'country', 'currency', 'status', 'created_at', 'updated_at'],
    seedTenants.map((t) => [
      t.id,
      t.name,
      nameKey(t.name),
      t.country,
      t.currency,
      t.status,
      datetime(t.createdAt),
      datetime(t.updatedAt),
    ]),
  ),
  insert(
    'audit_events',
    [
      'id',
      'tenant_id',
      'actor_id',
      'actor_role',
      'action',
      'entity',
      'entity_id',
      'before_state',
      'after_state',
      'at',
    ],
    seedAuditEvents.map((e) => [
      e.id,
      e.tenantId,
      e.actor.id,
      e.actor.role,
      e.action,
      e.entity,
      e.entityId,
      json(e.before),
      json(e.after),
      datetime(e.at),
    ]),
  ),
  insert(
    'categories',
    ['id', 'tenant_id', 'code', 'name', 'gl_account', 'active'],
    seedCategories.map((c) => [c.id, c.tenantId, c.code, c.name, c.glAccount, c.active]),
  ),
  insert(
    'policy_rules',
    [
      'id',
      'tenant_id',
      'category_id',
      'role',
      'limit_minor',
      'receipt_required_above_minor',
      'approval_levels',
    ],
    seedPolicyRules.map((r) => [
      r.id,
      r.tenantId,
      r.categoryId,
      r.role,
      r.limitMinor,
      r.receiptRequiredAboveMinor,
      r.approvalLevels,
    ]),
  ),
  insert(
    'employees',
    ['id', 'tenant_id', 'name', 'email', 'role', 'cost_center'],
    seedEmployees.map((e) => [e.id, e.tenantId, e.name, e.email, e.role, e.costCenter]),
  ),
]
  .filter((part) => part !== null)
  .join('\n');

writeFileSync(OUT, sql, 'utf8');
console.log(
  `Wrote ${OUT}: ${seedTenants.length} tenants, ${seedAuditEvents.length} audit events, ` +
    `${seedCategories.length} categories, ${seedPolicyRules.length} rules, ${seedEmployees.length} employees.`,
);
